# shellcheck shell=bash
# finding-triage.sh - orch.sh's finding-triage command: scan, apply and bundle.
# Its tests: scripts/test/orch/finding-triage.sh.
# Sourced by orch.sh, after common.sh and the ROOT block.

# The plugin's own label on a bundle issue - one ordinary issue that several
# filed findings are closed into as duplicates (finding-triage bundle).
readonly BUNDLE_LABEL="finding-bundle"

# The AI disclaimer line every comment finding triage posts opens with; both
# triage_comment_post and triage_comment_posted build the comment from it.
readonly TRIAGE_COMMENT_DISCLAIMER='> *This was generated by AI during triage.*'

# triage_state <labels>: the triage-role labels among the newline-separated
# <labels>, each by the repo's label for its role, comma-joined in
# TRIAGE_ROLES order - or - for none.
triage_state() {
  local role label out=""
  for role in $TRIAGE_ROLES; do
    triage_label_into label "$role"
    label_listed "$1" "$label" && out="${out:+$out,}$label"
  done
  printf '%s\n' "${out:--}"
}

# finding_scan_one <issue> <body> <default ref> <triage state> [<pr filter>]:
# the scan's one line for one finding - none when <pr filter> is given and the
# body names another PR. It settles the Location column, the result and the
# detail, then prints the six columns once, at its end.
finding_scan_one() {
  orch_load filed-finding
  orch_load lines-fate
  local n="$1" body="$2" ref="$3" roles="$4" pr file lines sha resolved_sha loc result detail fate
  local -A finding
  finding_body_parse "$body" finding
  pr="${finding[pr_number]}" file="${finding[file]}" lines="${finding[line]}" sha="${finding[sha]}"
  [ -z "${5:-}" ] || [ "$pr" = "$5" ] || return 0
  loc="$file:$lines" detail=""
  if [ -z "$file" ]; then
    loc=- result=unknown detail='body does not parse: no **Location:** line naming `<file>:<line>` at <SHA>'
  elif [ -z "$pr" ]; then
    result=unknown detail='body does not parse: no **PR:** line ending in a pull request URL'
  elif ! resolved_sha="$(git rev-parse --verify -q "$sha^{commit}")" &&
    { git fetch -q origin "refs/pull/$pr/head" >/dev/null 2>&1 || true
      ! resolved_sha="$(git rev-parse --verify -q "$sha^{commit}")"; }; then
    # A squash merge leaves the PR's head commit off every branch: the PR's own
    # head ref was fetched above, and still does not hold it.
    result=unknown detail="head SHA $sha is unreachable, even after fetching refs/pull/$pr/head"
  else
    lines_fate "$resolved_sha" "$ref" "$file" "${lines%%-*}" "${lines#*-}" fate detail
    case "$fate" in
      never-reached)
        result=unknown
        detail="no commit on the default branch since $sha touched $file:$lines - the difference is commits that never reached it" ;;
      *) result="$fate" ;;
    esac
  fi
  printf '%s\t%s\t%s\t%s\t%s\t%s\n' "$n" "${pr:--}" "$loc" "$result" "${detail:--}" "$roles"
}

# finding-triage scan [--all] [<issue> | --pr <n>]: read-only. Sorts each open
# filed finding still in needs-triage - or, with --all, whatever its triage
# label - against origin/<default>, one tab-separated line apiece: <issue>
# <pr> <file>:<line> <result> <detail> <triage state>.
cmd_finding_triage_scan() {
  orch_load filed-finding
  local usage="usage: orch.sh finding-triage scan [--all] [<issue> | --pr <n>]"
  # shellcheck disable=SC2034 # listed is issues_labelled_bodies_read's count out-param, unused here
  local all=false issue="" pr_filter="" triage sev n listed labels body default ref gh_err
  local -A found_labels=() found_bodies=()
  local args=() triage_filter=()
  while [ $# -gt 0 ]; do
    case "$1" in
      --all) ! $all || die "$usage"; all=true ;;
      --pr) [ -z "$pr_filter" ] && [ -n "${2:-}" ] || die "$usage"; pr_filter="$2"; shift ;;
      *) args+=("$1") ;;
    esac
    shift
  done
  case "${#args[@]}" in
    0) ;;
    1) [ -z "$pr_filter" ] && [ -n "${args[0]}" ] || die "$usage"; issue="${args[0]}" ;;
    *) die "$usage" ;;
  esac
  case "$issue$pr_filter" in *[!0-9]*) die "$usage" ;; esac
  triage_label_into triage needs-triage
  # A listed finding is read by its listing, labels and body together; an
  # explicit one by its single read, where it is checked. Both fill the same
  # two arrays, which the loop below walks without another GitHub call.
  if [ -n "$issue" ]; then
    open_issue_read "$issue" "issue #$issue is not open - finding triage takes open filed findings only" labels body
    has_filed_severity_label "$labels" \
      || die "issue #$issue is not a filed finding - it carries no review:<severity> label for a filed severity (review:${FILED_SEVERITIES// / or review:})"
    $all || label_listed "$labels" "$triage" \
      || die "issue #$issue is not in triage - it carries no '$triage' label"
    found_labels[$issue]="$labels"
    found_bodies[$issue]="$body"
  else
    # The labels besides each severity's: the triage label, unless --all.
    triage_filter=("$triage")
    ! $all || triage_filter=()
    for sev in $FILED_SEVERITIES; do
      issues_labelled_bodies_read found_labels found_bodies listed gh_err \
        "review:$sev" ${triage_filter[@]+"${triage_filter[@]}"} \
        || gh_die "list the review:$sev findings" "$gh_err"
    done
  fi
  default_branch_into default
  ref="refs/remotes/origin/$default"
  git fetch -q origin "+refs/heads/$default:$ref" >/dev/null 2>&1 \
    || die "could not fetch origin/$default"
  for n in $(printf '%s\n' ${found_labels[@]+"${!found_labels[@]}"} | sort -n); do
    finding_scan_one "$n" "${found_bodies[$n]}" "$ref" "$(triage_state "${found_labels[$n]}")" "$pr_filter"
  done
}

# triage_comment_post <err-var> <issue> <file>: posts <file> on the issue under
# the AI disclaimer every comment finding triage writes carries. Builds the
# comment in the current shell, where errexit holds, and dies naming <file>
# when it cannot (#1335): an unreadable file would otherwise post the
# disclaimer alone. Only the adapter call runs through gh_capture_err, so its
# stderr lands in <err-var> and its status is returned for the caller to word
# its own error. Same rules as gh_capture_err: current shell only, with
# _triage_comment_post_-prefixed locals.
triage_comment_post() {
  local _triage_comment_post_tmp _triage_comment_post_st=0
  temp_file_make _triage_comment_post_tmp \
    || die "could not create a temp file for the triage comment on issue #$2 - nothing was posted"
  { printf '%s\n\n' "$TRIAGE_COMMENT_DISCLAIMER" && cat "$3"; } >"$_triage_comment_post_tmp" || {
    rm -f "$_triage_comment_post_tmp"
    die "could not write the triage comment from $3 - nothing was posted on issue #$2"
  }
  gh_capture_err "$1" adapter_issue_comment "$2" "$_triage_comment_post_tmp" || _triage_comment_post_st=$?
  rm -f "$_triage_comment_post_tmp"
  return "$_triage_comment_post_st"
}

# triage_comment_posted <issue> <file>: succeeds when one of the issue's
# trusted comments (Trust module) already equals what triage_comment_post
# would post for <file>: the AI disclaimer line, a blank line, then <file>.
# Trailing newlines are trimmed from both sides and the compare is otherwise
# exact, per comment from the raw JSON. A gh failure dies as "gh could not read
# issue #<issue>'s comments", a comments answer that does not parse as "could
# not read issue #<issue>'s comments: its comments did not parse"; both before
# any write. Fails, printing nothing, when no comment matches or <file> cannot
# be read (triage_comment_post then dies naming it).
triage_comment_posted() {
  local kept want
  comments_trusted issue "read issue #$1's comments" "$1" kept
  want="$(printf '%s\n\n' "$TRIAGE_COMMENT_DISCLAIMER" && cat "$2")" \
    || return 1  # triage_comment_post dies naming the unreadable file
  jq -e --arg want "$want" 'any(.[]; (.body | sub("\n+$"; "")) == $want)' <<<"$kept" >/dev/null
}

# finding-triage apply <issue> <outcome> [--category <bug|enhancement>]
# --comment-file <file>: finding triage's one write to GitHub. Posts the
# comment under the AI disclaimer (skipped when an identical comment is already
# on the issue, so a re-run after a failed relabel or close posts it once),
# removes every triage-role label the issue
# carries other than the one the outcome sets, and either closes it
# (close-fixed: completed; wontfix: not planned, labelled wontfix) or labels it
# with its state, keeping review:<severity> and leaving exactly the one
# category asked for. Every state label is the repo's name for
# the role. Only a failed category-label create is forgiven; any other failed
# gh call dies.
cmd_finding_triage_apply() {
  local usage="usage: orch.sh finding-triage apply <issue> <close-fixed|wontfix> --comment-file <file>
       orch.sh finding-triage apply <issue> <ready-for-agent|ready-for-human> --category <bug|enhancement> --comment-file <file>"
  local issue="${1:-}" outcome="${2:-}" category="" file="" state labels role label outcome_label stale_category gh_err
  # The relabel's --remove options, possibly none: close-fixed, where they are
  # the whole relabel, then makes no edit at all.
  local remove_opts=()
  [ $# -ge 2 ] || die "$usage"
  shift 2
  while [ $# -gt 0 ]; do
    case "$1" in
      --category)     [ $# -ge 2 ] || die "$usage"; category="$2"; shift 2 ;;
      --comment-file) [ $# -ge 2 ] || die "$usage"; file="$2"; shift 2 ;;
      *) die "$usage" ;;
    esac
  done
  case "$issue" in ''|*[!0-9]*) die "$usage" ;; esac
  case "$outcome" in
    close-fixed|wontfix)
      [ -z "$category" ] || die "--category is for an outcome that stays open, not $outcome" ;;
    ready-for-agent|ready-for-human)
      [ -n "$category" ] || die "$outcome needs --category <bug|enhancement>"
      stale_category="$(category_other "$category")" \
        || die "unknown --category '$category' - expected bug or enhancement" ;;
    *) die "$usage" ;;
  esac
  [ -n "$file" ] || die "$usage"
  [ -f "$file" ] || die "comment file not found: $file"

  # Only the labels are wanted: the state is the read's throwaway half, rather
  # than a third, near-identical label read added beside
  # adapter_issue_state_labels and adapter_issue_title_labels.
  issue_state_labels_read "$issue" state labels gh_err \
    || gh_die "read issue #$issue" "$gh_err"
  # Every triage-role label the issue carries but the outcome does not set
  # goes, so an already-triaged finding ends in the one state the outcome
  # sets. Remove only what the issue carries: gh refuses to remove a label the
  # repo does not have at all.
  for role in $TRIAGE_ROLES; do
    [ "$role" != "$outcome" ] || continue
    triage_label_into label "$role"
    if label_listed "$labels" "$label"; then remove_opts+=(--remove "$label"); fi
  done

  triage_label_into outcome_label "$outcome"
  triage_comment_posted "$issue" "$file" || {
    triage_comment_post gh_err "$issue" "$file" || gh_die "comment on issue #$issue" "$gh_err"
  }

  case "$outcome" in
    close-fixed)
      gh_or_die "relabel issue #$issue" \
        adapter_issue_relabel "$issue" ${remove_opts[@]+"${remove_opts[@]}"}
      gh_or_die "close issue #$issue" adapter_issue_close "$issue" --reason completed ;;
    wontfix)
      gh_or_die "relabel issue #$issue" \
        adapter_issue_relabel "$issue" --add "$outcome_label" \
        ${remove_opts[@]+"${remove_opts[@]}"}
      gh_or_die "close issue #$issue" adapter_issue_close "$issue" --reason "not planned" ;;
    *)
      category_label_ensure "$category"
      if label_listed "$labels" "$stale_category"; then remove_opts+=(--remove "$stale_category"); fi
      gh_or_die "relabel issue #$issue" \
        adapter_issue_relabel "$issue" --add "$outcome_label" --add "$category" \
        ${remove_opts[@]+"${remove_opts[@]}"} ;;
  esac
}

# bundle_member_check <issue> <labels>: dies unless open issue #<issue>, whose
# labels (one per line) the caller has read, can be
# a bundle's member - carrying a filed-severity review:<severity> label,
# exactly one of the repo's ready-for-agent and ready-for-human labels and none
# of its needs-triage, needs-info and wontfix - naming the issue and why.
# Makes no read: the caller's one state read decided the issue is open.
bundle_member_check() {
  orch_load filed-finding
  local __bmc_labels="$2" __bmc_role __bmc_label __bmc_ready=""
  has_filed_severity_label "$__bmc_labels" \
    || die "issue #$1 is not a filed finding - it carries no review:<severity> label for a filed severity (review:${FILED_SEVERITIES// / or review:})"
  for __bmc_role in needs-triage needs-info wontfix; do
    triage_label_into __bmc_label "$__bmc_role"
    ! label_listed "$__bmc_labels" "$__bmc_label" \
      || die "issue #$1 carries '$__bmc_label' - a bundle takes findings already triaged to ready-for-agent or ready-for-human only"
  done
  for __bmc_role in ready-for-agent ready-for-human; do
    triage_label_into __bmc_label "$__bmc_role"
    label_listed "$__bmc_labels" "$__bmc_label" || continue
    [ -z "$__bmc_ready" ] \
      || die "issue #$1 carries both '$__bmc_ready' and '$__bmc_label' - a member carries exactly one"
    __bmc_ready="$__bmc_label"
  done
  if [ -z "$__bmc_ready" ]; then
    local __bmc_agent __bmc_human
    triage_label_into __bmc_agent ready-for-agent
    triage_label_into __bmc_human ready-for-human
    die "issue #$1 carries neither '$__bmc_agent' nor '$__bmc_human' - triage it with $(finding_triage_cmd) first"
  fi
}

# finding-triage bundle --title <t> --body-file <f> --state <ready-for-agent|
# ready-for-human> --category <bug|enhancement> <member>...: creates one
# bundle issue - the title and body as given, labelled finding-bundle, the
# repo's label for the state and the category, never a review: label - prints
# its number, then comments each member `Bundled into #B` under the AI
# disclaimer and closes it as a duplicate of the bundle, keeping its labels,
# reading its state back. Every member is checked before any write. The
# state and category may be stricter than the members', never looser.
# --into <B> <member>... is the resume form: it checks that B is an open issue
# labelled finding-bundle and every member not already closed into B (a
# trusted `Bundled into #B` comment) the same way (one is enough), skips the
# ones already closed, then only comments, closes and reads back - it never
# edits B. Any member failure dies naming the bundle and the members left open
# (or not confirmed closed, where the close may have landed), with the --into
# command that resumes.
cmd_finding_triage_bundle() {
  local usage="usage: orch.sh finding-triage bundle --title <t> --body-file <f> --state <ready-for-agent|ready-for-human> --category <bug|enhancement> <member>...
       orch.sh finding-triage bundle --into <B> <member>..."
  local title="" file="" state="" category="" into="" have_title=false m labels human_label b state_label
  local members=() seen=" " mstate err
  while [ $# -gt 0 ]; do
    case "$1" in
      --title)     [ $# -ge 2 ] || die "$usage"; title="$2"; have_title=true; shift 2 ;;
      --body-file) [ $# -ge 2 ] || die "$usage"; file="$2"; shift 2 ;;
      --state)     [ $# -ge 2 ] || die "$usage"; state="$2"; shift 2 ;;
      --category)  [ $# -ge 2 ] || die "$usage"; category="$2"; shift 2 ;;
      --into)      [ $# -ge 2 ] || die "$usage"; into="$2"; shift 2 ;;
      *) members+=("$1"); shift ;;
    esac
  done
  [ ${#members[@]} -gt 0 ] || die "$usage"
  for m in "${members[@]}"; do
    case "$m" in ''|*[!0-9]*) die "$usage" ;; esac
  done
  if [ -n "$into" ]; then
    case "$into" in *[!0-9]*) die "$usage" ;; esac
    ! $have_title && [ -z "$file$state$category" ] || die "$usage"
    local b_labels
    open_issue_read --hint "no member was touched" "$into" "bundle #$into is not open - --into resumes an open bundle only" b_labels
    label_listed "$b_labels" "$BUNDLE_LABEL" \
      || die "issue #$into carries no '$BUNDLE_LABEL' label - --into resumes a bundle only"
  else
    $have_title && [ -n "$title" ] && [ -n "$file" ] && [ -n "$state" ] && [ -n "$category" ] || die "$usage"
    case "$state" in ready-for-agent|ready-for-human) ;; *) die "$usage" ;; esac
    category_other "$category" >/dev/null || die "unknown --category '$category' - expected bug or enhancement"
    [ -f "$file" ] || die "body file not found: $file"
    [ ${#members[@]} -ge 2 ] || die "a new bundle needs at least 2 members - got #${members[0]} alone"
    triage_label_into human_label ready-for-human
  fi

  local pending=()
  for m in "${members[@]}"; do
    ! word_listed "$seen" "$m" || die "issue #$m is named twice"
    seen="$seen$m "
    issue_state_labels_read "$m" mstate labels err \
      || gh_die --hint "no member was touched" "read issue #$m" "$err"
    if [ "$mstate" != OPEN ]; then
      if [ -n "$into" ] && bundle_member_done "$into" "$m"; then continue; fi
      die "issue #$m is not open - a bundle takes open filed findings only"
    fi
    pending+=("$m")
    bundle_member_check "$m" "$labels"
    if [ -z "$into" ]; then
      [ "$state" != ready-for-agent ] || ! label_listed "$labels" "$human_label" \
        || die "--state ready-for-agent, but issue #$m carries '$human_label' - a bundle is ready-for-human whenever any member is"
      [ "$category" != enhancement ] || ! label_listed "$labels" bug \
        || die "--category enhancement, but issue #$m carries 'bug' - a bundle is a bug whenever any member is"
    fi
  done

  if [ -n "$into" ]; then
    bundle_members_close "$into" ${pending[@]+"${pending[@]}"}
    return
  fi

  # The finding-bundle label is the plugin's, but created only where missing,
  # as the triage labels are: a failed create is forgiven, and a truly missing
  # label then fails the issue create.
  adapter_label_create "$BUNDLE_LABEL" c5def5 "Several filed findings worked as one" 2>/dev/null || true
  triage_label_into state_label "$state"
  category_label_ensure "$category"
  gh_or_die --hint "no member was touched" --out b "create the bundle issue" \
    adapter_issue_create "$title" "$file" "$BUNDLE_LABEL" "$state_label" "$category"
  printf '%s\n' "$b"
  bundle_members_close "$b" "${members[@]}"
}

# bundle_member_done <B> <member>: succeeds when a trusted comment on the
# not-open member #<member> holds `Bundled into #B`, which the close loop posts
# before it closes; fails otherwise. It reads no state: the caller has. A failed
# or unparseable comments read dies naming the member, before any write.
bundle_member_done() {
  local comments
  comments_rendered --hint "no member was touched" issue \
    "read issue #$2's comments" "$2" comments
  grep -qE "Bundled into #$1([^0-9]|\$)" <<<"$comments"
}

# bundle_members_close <B> <member>...: closes each member into bundle #B, in
# order - reads its comments and, unless one already holds `Bundled into #B`,
# posts that under the AI disclaimer; closes it as a duplicate of B; reads its
# state back as CLOSED. The first member that fails dies naming the bundle,
# what failed, the members left open (not confirmed closed where the close
# may have landed) - that one and every one after it - and the --into command
# that resumes. --into skips a member already closed into B before this runs.
bundle_members_close() {
  local b="$1" comment_file m i=0 comments kept state why left err held reason
  shift
  [ $# -gt 0 ] || return 0 # every member was already closed into B
  local members=("$@")
  temp_file_make comment_file || die "could not create a temp file for the bundle comments"
  printf 'Bundled into #%s\n' "$b" >"$comment_file"
  for m in "${members[@]}"; do
    why=""
    held="left open"
    if ! { comments_trusted_read issue "$m" kept reason && comments="$(comments_render <<<"$kept")"; }; then
      if [ -n "$reason" ]; then why="gh could not read member #$m's comments: $reason"
      else why="could not read member #$m's comments: its comments did not parse"; fi
    elif ! grep -qE "Bundled into #$b([^0-9]|\$)" <<<"$comments" \
      && ! triage_comment_post err "$m" "$comment_file"; then
      why="gh could not comment on member #$m: $(gh_reason "$err")"
    elif ! gh_capture_err err adapter_issue_close "$m" --duplicate-of "$b"; then
      why="gh could not close member #$m as a duplicate: $(gh_reason "$err") - --duplicate-of needs gh 2.102 or newer"
      held="not confirmed closed"
    elif ! gh_capture state err adapter_issue_state "$m"; then
      why="gh could not read member #$m's state back: $(gh_reason "$err")"
      held="not confirmed closed"
    elif [ "$state" != CLOSED ]; then
      why="member #$m did not read back as closed"
      held="not confirmed closed"
    fi
    if [ -n "$why" ]; then
      rm -f "$comment_file"
      left="${members[*]:$i}"
      die "bundle #$b: $why - members $held: #${left// / #}; resume with: orch.sh finding-triage bundle --into $b $left"
    fi
    i=$((i + 1))
  done
  rm -f "$comment_file"
}

cmd_finding_triage() {
  local op="${1:-}"
  shift || true
  case "$op" in
    scan) cmd_finding_triage_scan "$@" ;;
    apply) cmd_finding_triage_apply "$@" ;;
    bundle) cmd_finding_triage_bundle "$@" ;;
    *) die "usage: orch.sh finding-triage <scan|apply|bundle> ..." ;;
  esac
}
