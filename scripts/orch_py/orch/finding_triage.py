"""orch.sh's finding-triage noun (ADR-0067): finding triage's scan, apply and
bundle, on the issues a review loop filed (ADR-0031).

run(argv) takes the arguments after `finding-triage`, as orch.sh hands them
on, and returns the exit code; a usage error, a refusal or a failed gh call
dies through orch.common.die, every death exit 1. Every verb keeps the bash
noun's usage lines, the order it checks its arguments in, its stdout and its
`orch:` messages.

The scan reads what became of each finding's lines through a Lines fate
function it is handed - orch.lines_fate's own unless a test hands in another -
and every git command through the git adapter's named operations.

apply and bundle are its writes. Each comment they post opens with the AI
disclaimer and goes from a temporary file, made by the temporary-file maker
the noun is handed - tempfile.mkstemp unless a test hands in another - and
removed on every path, a death included.
"""
from __future__ import annotations

import os
import re
import tempfile
from typing import Callable, Dict, List, Mapping, Optional, Tuple

from orch.base import default_branch
from orch.common import die, plain_number, temp_text_file
from orch import comments
from orch.filed_finding import (
    FILED_SEVERITIES,
    category_label_ensure,
    category_other,
    filed_severity_label_or_die,
    finding_body_parse,
)
from orch.gh import (
    GhFailed,
    adapter,
    gh_die,
    gh_or_die,
    gh_reason,
    label_listed,
    open_issue_read,
)
from orch.git import Git
from orch.host import finding_triage_cmd
from orch.lines_fate import NEVER_REACHED, lines_fate
from orch.repo import RepoPin
from orch.root import checkout_root
from orch.triage_labels import TRIAGE_ROLES, TriageLabels

# The verbs, each a FindingTriage method of its name. docs_lint.sh reads this
# line as the verbs the noun dispatches, so it stays one `OPS = "<verb>|..."`
# line.
OPS = "scan|apply|bundle"

SCAN_USAGE = "usage: orch.sh finding-triage scan [--all] [<issue> | --pr <n>]"

NO_LOCATION = "body does not parse: no **Location:** line naming `<file>:<line>` at <SHA>"
NO_PR = "body does not parse: no **PR:** line ending in a pull request URL"

APPLY_USAGE = (
    "usage: orch.sh finding-triage apply <issue> <close-fixed|wontfix> --comment-file <file>\n"
    "       orch.sh finding-triage apply <issue> <ready-for-agent|ready-for-human>"
    " --category <bug|enhancement> --comment-file <file>"
)

BUNDLE_USAGE = (
    "usage: orch.sh finding-triage bundle --title <t> --body-file <f> --state"
    " <ready-for-agent|ready-for-human> --category <bug|enhancement> <member>...\n"
    "       orch.sh finding-triage bundle --into <B> <member>..."
)

# The AI disclaimer line every comment finding triage posts opens with.
TRIAGE_COMMENT_DISCLAIMER = "> *This was generated by AI during triage.*"

# The plugin's own label on a bundle issue - one ordinary issue several filed
# findings are closed into as duplicates - with its colour and description.
BUNDLE_LABEL = ("finding-bundle", "c5def5", "Several filed findings worked as one")

# The hint on every death before bundle's first write.
UNTOUCHED = "no member was touched"


class FindingTriage:
    """The verbs, on the gh adapter <gh>, in the checkout <git> reads, its
    repo pinned by <pin>, with <env> naming the host and the knobs and
    <fate> the Lines fate function the scan reads."""

    def __init__(self, gh, git, env: Mapping[str, str], pin, fate: Callable,
                 mkstemp: Callable[[], Tuple[int, str]] = tempfile.mkstemp) -> None:
        self.gh = gh
        self.git = git
        self.env = env
        self.pin = pin
        self.fate = fate
        self.mkstemp = mkstemp
        self.triage_labels = TriageLabels(git.toplevel)

    def triage_state(self, labels: List[str]) -> str:
        """The triage-role labels among <labels>, each by the repo's label
        for its role, comma-joined in TRIAGE_ROLES order - or - for none."""
        held = [label for label in map(self.triage_labels.label, TRIAGE_ROLES)
                if label_listed(labels, label)]
        return ",".join(held) or "-"

    # --- scan ---

    def scan(self, args: List[str]) -> int:
        """Read-only. Sorts each open filed finding still in needs-triage -
        or, with --all, whatever its triage label - against
        origin/<default>, one tab-separated line apiece, in issue order:
        <issue> <pr> <file>:<line> <result> <detail> <triage state>."""
        every, issue, pr_filter = scan_args(args)
        triage = self.triage_labels.label("needs-triage")
        # A listed finding is read by its listing, labels and body together;
        # an explicit one by its single read, where it is checked. Each is
        # keyed by its number as it prints: an explicit one as given, leading
        # zeros kept, as the bash noun printed it.
        found: Dict[str, Tuple[List[str], str]] = {}
        if issue:
            labels, body = open_issue_read(
                self.gh, issue,
                "issue #%s is not open - finding triage takes open filed findings only" % issue,
                body=True)
            filed_severity_label_or_die(issue, labels)
            if not every and not label_listed(labels, triage):
                die("issue #%s is not in triage - it carries no '%s' label" % (issue, triage))
            found[issue] = (labels, body)
        else:
            others = [] if every else [triage]
            for sev in FILED_SEVERITIES:
                listed = gh_or_die("list the review:%s findings" % sev,
                                   self.gh.issues_labelled_bodies, "review:" + sev, *others)
                for row in listed:
                    found[str(row.number)] = (row.labels, row.body)
        branch = default_branch(self.gh, self.git, self.pin).name
        if not self.git.fetch_default_branch(branch):
            die("could not fetch origin/" + branch)
        ref = "refs/remotes/origin/" + branch
        for n in sorted(found, key=int):
            labels, body = found[n]
            line = self.scan_one(n, body, ref, self.triage_state(labels), pr_filter)
            if line is not None:
                print(line)
        return 0

    def scan_one(self, n: str, body: str, ref: str, roles: str,
                 pr_filter: str) -> Optional[str]:
        """The scan's line for one finding; None when <pr_filter> is given
        and the body names another PR."""
        finding = finding_body_parse(body)
        pr, path, lines, sha = finding.pr_number, finding.file, finding.line, finding.sha
        if pr_filter and pr != pr_filter:
            return None
        location, detail = "%s:%s" % (path, lines), ""
        if not path:
            location, result, detail = "-", "unknown", NO_LOCATION
        elif not pr:
            result, detail = "unknown", NO_PR
        else:
            resolved = self.git.resolve_commit(sha)
            if resolved is None:
                # A squash merge leaves the PR's head commit off every branch:
                # the PR's own head ref is fetched, once, in case it holds it.
                self.git.fetch_pr_head(pr)
                resolved = self.git.resolve_commit(sha)
            if resolved is None:
                result = "unknown"
                detail = "head SHA %s is unreachable, even after fetching refs/pull/%s/head" % (
                    sha, pr)
            else:
                start, _, end = lines.partition("-")
                result, detail = self.fate(self.git, resolved, ref, path, int(start),
                                           int(end or start))
                if result == NEVER_REACHED:
                    result = "unknown"
                    detail = ("no commit on the default branch since %s touched %s:%s - the"
                              " difference is commits that never reached it" % (sha, path, lines))
        return "\t".join([n, pr or "-", location, result, detail or "-", roles])


    # --- apply ---

    def apply(self, args: List[str]) -> int:
        """`apply <issue> <outcome> [--category <bug|enhancement>]
        --comment-file <file>`: finding triage's one write to GitHub. Posts
        the comment under the AI disclaimer (skipped when an identical
        trusted comment is already on the issue, so a re-run after a failed
        relabel or close posts it once), removes every triage-role label the
        issue carries other than the one the outcome sets, and either closes
        it (close-fixed: completed; wontfix: not planned, labelled wontfix)
        or labels it with its state, keeping review:<severity> and leaving
        exactly the one category asked for. Only a failed category-label
        create is forgiven; any other failed gh call dies."""
        issue, outcome, category, path = apply_args(args)
        n = int(issue)
        _, labels = gh_or_die("read issue #" + issue, self.gh.issue_state_labels, n)
        # Remove only what the issue carries: gh refuses to remove a label
        # the repo does not have at all.
        remove = [label for label in (self.triage_labels.label(role) for role in TRIAGE_ROLES
                                      if role != outcome)
                  if label_listed(labels, label)]
        outcome_label = self.triage_labels.label(outcome)
        if not self.triage_comment_posted(issue, path):
            try:
                self.triage_comment_post(issue, path)
            except GhFailed as failed:
                gh_die("comment on issue #" + issue, failed.stderr)
        relabel = "relabel issue #" + issue
        close = "close issue #" + issue
        if outcome == "close-fixed":
            gh_or_die(relabel, self.gh.issue_relabel, n, remove=remove)
            gh_or_die(close, self.gh.issue_close, n, reason="completed")
        elif outcome == "wontfix":
            gh_or_die(relabel, self.gh.issue_relabel, n, add=[outcome_label], remove=remove)
            gh_or_die(close, self.gh.issue_close, n, reason="not planned")
        else:
            category_label_ensure(self.gh, category)
            stale = category_other(category)
            if label_listed(labels, stale):
                remove.append(stale)
            gh_or_die(relabel, self.gh.issue_relabel, n, add=[outcome_label, category],
                      remove=remove)
        return 0

    # --- bundle ---

    def bundle(self, args: List[str]) -> int:
        """`bundle --title <t> --body-file <f> --state <ready-for-agent|
        ready-for-human> --category <bug|enhancement> <member>...`: creates
        one bundle issue - the title and body as given, labelled
        finding-bundle, the repo's label for the state and the category,
        never a review: label - prints its number, then closes each member
        into it. Every member is checked before any write; the state and
        category may be stricter than the members', never looser.

        `bundle --into <B> <member>...` resumes: B must be an open
        finding-bundle issue, each member not already closed into B (a
        trusted `Bundled into #B` comment) is checked the same way (one is
        enough), and B is never edited."""
        title, path, state, category, into, members = bundle_args(args)
        if into:
            bundle_labels, _ = open_issue_read(
                self.gh, into, "bundle #%s is not open - --into resumes an open bundle only" % into,
                hint=UNTOUCHED)
            if not label_listed(bundle_labels, BUNDLE_LABEL[0]):
                die("issue #%s carries no '%s' label - --into resumes a bundle only"
                    % (into, BUNDLE_LABEL[0]))
        else:
            if not title or not path or not state or not category:
                die(BUNDLE_USAGE)
            if state not in ("ready-for-agent", "ready-for-human"):
                die(BUNDLE_USAGE)
            if category_other(category) is None:
                die("unknown --category '%s' - expected bug or enhancement" % category)
            if not os.path.isfile(path):
                die("body file not found: " + path)
            if len(members) < 2:
                die("a new bundle needs at least 2 members - got #%s alone" % members[0])
        human = self.triage_labels.label("ready-for-human")

        pending: List[str] = []
        seen = set()
        for m in members:
            if m in seen:
                die("issue #%s is named twice" % m)
            seen.add(m)
            member_state, labels = gh_or_die("read issue #" + m, self.gh.issue_state_labels,
                                             int(m), hint=UNTOUCHED)
            if member_state != "OPEN":
                if into and self.bundle_member_done(into, m):
                    continue
                die("issue #%s is not open - a bundle takes open filed findings only" % m)
            pending.append(m)
            self.bundle_member_check(m, labels)
            if not into:
                if state == "ready-for-agent" and label_listed(labels, human):
                    die("--state ready-for-agent, but issue #%s carries '%s' - a bundle is"
                        " ready-for-human whenever any member is" % (m, human))
                if category == "enhancement" and label_listed(labels, "bug"):
                    die("--category enhancement, but issue #%s carries 'bug' - a bundle is a"
                        " bug whenever any member is" % m)

        if into:
            self.bundle_members_close(into, pending)
            return 0
        # The finding-bundle label is the plugin's, but created only where
        # missing, as the triage labels are: a failed create is forgiven, and
        # a truly missing label then fails the issue create.
        try:
            self.gh.label_create(*BUNDLE_LABEL)
        except GhFailed:
            pass
        category_label_ensure(self.gh, category)
        b = gh_or_die("create the bundle issue", self.gh.issue_create, title, path,
                      [BUNDLE_LABEL[0], self.triage_labels.label(state), category],
                      hint=UNTOUCHED)
        print(b)
        self.bundle_members_close(str(b), members)
        return 0

    def bundle_member_check(self, m: str, labels: List[str]) -> None:
        """Dies unless open issue #<m>, carrying <labels>, can be a bundle's
        member - carrying a filed-severity review:<severity> label, exactly
        one of the repo's ready-for-agent and ready-for-human labels and none
        of its needs-triage, needs-info and wontfix - naming the issue and
        why."""
        filed_severity_label_or_die(m, labels)
        for role in ("needs-triage", "needs-info", "wontfix"):
            label = self.triage_labels.label(role)
            if label_listed(labels, label):
                die("issue #%s carries '%s' - a bundle takes findings already triaged to"
                    " ready-for-agent or ready-for-human only" % (m, label))
        ready = ""
        for role in ("ready-for-agent", "ready-for-human"):
            label = self.triage_labels.label(role)
            if not label_listed(labels, label):
                continue
            if ready:
                die("issue #%s carries both '%s' and '%s' - a member carries exactly one"
                    % (m, ready, label))
            ready = label
        if not ready:
            die("issue #%s carries neither '%s' nor '%s' - triage it with %s first"
                % (m, self.triage_labels.label("ready-for-agent"),
                   self.triage_labels.label("ready-for-human"), finding_triage_cmd(self.env)))

    def bundle_member_done(self, b: str, m: str) -> bool:
        """Whether a trusted comment on the not-open member #<m> holds
        `Bundled into #<b>`, which the close loop posts before it closes. A
        failed or unparsed comments read dies naming the member, before any
        write."""
        kept = comments.trusted(self.gh, "read issue #%s's comments" % m, m, hint=UNTOUCHED)
        return bundled_marker(b).search(comments.render(kept)) is not None

    def bundle_members_close(self, b: str, members: List[str]) -> None:
        """Closes each member into bundle #<b>, in order: unless a trusted
        comment already holds `Bundled into #<b>`, posts that under the AI
        disclaimer; closes it as a duplicate of <b>; reads its state back as
        CLOSED. The first member that fails dies naming the bundle, what
        failed, the members left open - not confirmed closed where the close
        may have landed - that one and every one after it, and the --into
        command that resumes."""
        if not members:
            return  # every member was already closed into B
        with temp_text_file("Bundled into #%s\n" % b,
                            "could not create a temp file for the bundle comments",
                            mkstemp=self.mkstemp) as comment_file:
            marker = bundled_marker(b)
            for i, m in enumerate(members):
                why, held = self.bundle_member_close(b, m, comment_file, marker)
                if why:
                    left = members[i:]
                    die("bundle #%s: %s - members %s: %s; resume with: orch.sh finding-triage"
                        " bundle --into %s %s"
                        % (b, why, held, " ".join("#" + n for n in left), b, " ".join(left)))

    def bundle_member_close(self, b: str, m: str, comment_file: str,
                            marker) -> Tuple[str, str]:
        """Closes member #<m> into bundle #<b>: ("", "") when it read back
        closed, else what failed and whether the member is "left open" or
        "not confirmed closed"."""
        kept, reason = comments.trusted_read(self.gh, m)
        if kept is None:
            if reason:
                return "gh could not read member #%s's comments: %s" % (m, reason), "left open"
            return ("could not read member #%s's comments: its comments did not parse" % m,
                    "left open")
        if marker.search(comments.render(kept)) is None:
            try:
                self.triage_comment_post(m, comment_file)
            except GhFailed as failed:
                return ("gh could not comment on member #%s: %s" % (m, gh_reason(failed.stderr)),
                        "left open")
        unconfirmed = "not confirmed closed"
        try:
            self.gh.issue_close(int(m), duplicate_of=int(b))
        except GhFailed as failed:
            return ("gh could not close member #%s as a duplicate: %s - --duplicate-of needs gh"
                    " 2.102 or newer" % (m, gh_reason(failed.stderr)), unconfirmed)
        try:
            closed = self.gh.issue_state(int(m))
        except GhFailed as failed:
            return ("gh could not read member #%s's state back: %s"
                    % (m, gh_reason(failed.stderr)), unconfirmed)
        if closed != "CLOSED":
            return "member #%s did not read back as closed" % m, unconfirmed
        return "", ""

    # --- the triage comment ---

    def triage_comment_post(self, issue: str, path: str) -> None:
        """Posts the file at <path> on the issue under the AI disclaimer,
        from a temporary file removed on every path; a gh failure raises
        GhFailed. Dies, posting nothing, when the temporary file cannot be
        made, or when the comment cannot be built from <path> into it - an
        unreadable file would otherwise post the disclaimer alone (#1335)."""
        unwritten = ("could not write the triage comment from %s - nothing was posted on"
                     " issue #%s" % (path, issue))
        try:
            with open(path, "rb") as source:
                text = source.read().decode("utf-8", "surrogateescape")
        except OSError:
            die(unwritten)
        with temp_text_file(TRIAGE_COMMENT_DISCLAIMER + "\n\n" + text,
                            "could not create a temp file for the triage comment on issue #%s"
                            " - nothing was posted" % issue,
                            unwritten, mkstemp=self.mkstemp) as tmp:
            self.gh.issue_comment(int(issue), tmp)

    def triage_comment_posted(self, issue: str, path: str) -> bool:
        """Whether one of the issue's trusted comments already equals what
        triage_comment_post would post for <path>: trailing newlines trimmed
        from both sides, the compare otherwise exact. A failed or unparsed
        comments read dies, before any write. False when <path> cannot be
        read: triage_comment_post then dies naming it."""
        kept = comments.trusted(self.gh, "read issue #%s's comments" % issue, issue)
        try:
            with open(path, "rb") as f:
                text = f.read().decode("utf-8", "surrogateescape")
        except OSError:
            return False
        want = (TRIAGE_COMMENT_DISCLAIMER + "\n\n" + text).rstrip("\n")
        return any(isinstance(c.get("body"), str) and c["body"].rstrip("\n") == want
                   for c in kept)


def apply_args(args: List[str]) -> Tuple[str, str, str, str]:
    """apply's issue, outcome, category ("" when not given) and comment
    file, checked in the bash verb's order: the shape, the issue a plain
    number, the outcome and its category, then the comment file given and
    there."""
    if len(args) < 2:
        die(APPLY_USAGE)
    issue, outcome = args[0], args[1]
    category, path = "", ""
    i = 2
    while i < len(args):
        if args[i] not in ("--category", "--comment-file") or i + 1 >= len(args):
            die(APPLY_USAGE)
        if args[i] == "--category":
            category = args[i + 1]
        else:
            path = args[i + 1]
        i += 2
    if not plain_number(issue):
        die(APPLY_USAGE)
    if outcome in ("close-fixed", "wontfix"):
        if category:
            die("--category is for an outcome that stays open, not " + outcome)
    elif outcome in ("ready-for-agent", "ready-for-human"):
        if not category:
            die(outcome + " needs --category <bug|enhancement>")
        if category_other(category) is None:
            die("unknown --category '%s' - expected bug or enhancement" % category)
    else:
        die(APPLY_USAGE)
    if not path:
        die(APPLY_USAGE)
    if not os.path.isfile(path):
        die("comment file not found: " + path)
    return issue, outcome, category, path


def bundle_args(
    args: List[str],
) -> Tuple[Optional[str], str, str, str, str, List[str]]:
    """bundle's title (None when not given), body file, state, category,
    --into bundle and members, each "" when not given. Dies with the usage
    on an option with no value, on no member, on a member or bundle that is
    not a plain number, or on --into given with any option of the new
    form."""
    values: Dict[str, str] = {}
    title: Optional[str] = None
    members: List[str] = []
    i = 0
    while i < len(args):
        arg = args[i]
        if arg in ("--title", "--body-file", "--state", "--category", "--into"):
            if i + 1 >= len(args):
                die(BUNDLE_USAGE)
            if arg == "--title":
                title = args[i + 1]
            else:
                values[arg] = args[i + 1]
            i += 2
            continue
        members.append(arg)
        i += 1
    if not members or not all(plain_number(m) for m in members):
        die(BUNDLE_USAGE)
    path, state, category, into = (values.get(flag, "") for flag in (
        "--body-file", "--state", "--category", "--into"))
    if into and (not plain_number(into) or title is not None or path or state or category):
        die(BUNDLE_USAGE)
    return title, path, state, category, into, members


def bundled_marker(b: str):
    """The `Bundled into #<b>` a comment holds once its member was closed
    into bundle #<b>, never matching a longer number."""
    return re.compile(r"Bundled into #%s([^0-9]|$)" % b, re.MULTILINE)


def scan_args(args: List[str]) -> Tuple[bool, str, str]:
    """scan's arguments, as the bash verb reads them: whether --all is
    given, the explicit issue and the --pr filter, each "" when not given.
    Dies with the usage on any other shape, or on an issue or a PR that is
    not a plain number."""
    every, pr_filter, rest = False, "", []
    i = 0
    while i < len(args):
        arg = args[i]
        if arg == "--all":
            if every:
                die(SCAN_USAGE)
            every = True
        elif arg == "--pr":
            if pr_filter or i + 1 >= len(args) or not args[i + 1]:
                die(SCAN_USAGE)
            pr_filter = args[i + 1]
            i += 1
        else:
            rest.append(arg)
        i += 1
    if len(rest) > 1 or (rest and (pr_filter or not rest[0])):
        die(SCAN_USAGE)
    issue = rest[0] if rest else ""
    if (issue or pr_filter) and not plain_number(issue + pr_filter):
        die(SCAN_USAGE)
    return every, issue, pr_filter


def run(
    argv: List[str],
    gh=None,
    git=None,
    env: Optional[Mapping[str, str]] = None,
    pin=None,
    fate: Callable = lines_fate,
    mkstemp: Callable[[], Tuple[int, str]] = tempfile.mkstemp,
) -> int:
    """`orch.sh finding-triage <op> ...`: the real adapters, the process's
    environment, the real Lines fate and the real temporary-file maker
    unless a test hands in others.
    Outside a checkout it dies first, as orch.sh does, whatever the op."""
    env = os.environ if env is None else env
    git = Git() if git is None else git
    checkout_root(git, env)
    pin = RepoPin(env, git) if pin is None else pin
    noun = FindingTriage(adapter(env, pin=pin) if gh is None else gh, git, env, pin, fate,
                         mkstemp)
    op = argv[0] if argv else ""
    if op not in OPS.split("|"):
        die("usage: orch.sh finding-triage <scan|apply|bundle> ...")
    return getattr(noun, op)(argv[1:])
