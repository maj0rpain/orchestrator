def closed_into(store, n):
    """Member #n's state, close reason and the issue it is a duplicate of."""
    return state_of(store, n) + ((read(store, "issues", n, "duplicate_of") or "").rstrip("\n"),)


def test_bundle_files_the_bundle_and_closes_each_member_into_it(seed, store, new_bundle):
    triaged(seed, 11, "review:major", "ready-for-agent", "bug")
    triaged(seed, 13, "review:nit", "ready-for-human", "enhancement")
    seed.next_issue(20)

    assert new_bundle("ready-for-human", "bug", "11", "13") == (0, "20\n", "")
    assert state_of(store, 20) == ("OPEN", "")
    assert read(store, "issues", 20, "title") == "Area (2 findings)\n"
    assert read(store, "issues", 20, "body") == BUNDLE_BODY
    assert sorted(labels_of(store, 20)) == ["bug", "finding-bundle", "ready-for-human"]
    assert "finding-bundle\tc5def5\tSeveral filed findings worked as one\n" in read(store, "labels")
    assert "bug\td73a4a\tSomething isn't working\n" in read(store, "labels")
    for m in (11, 13):
        assert comments_of(store, m) == [bundled_into(20)]
        assert closed_into(store, m) == ("CLOSED", "duplicate", "20")
    assert sorted(labels_of(store, 11)) == ["bug", "ready-for-agent", "review:major"]
    assert sorted(labels_of(store, 13)) == ["enhancement", "ready-for-human", "review:nit"]


