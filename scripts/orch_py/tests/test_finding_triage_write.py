EVERY_ROLE = ("needs-triage", "needs-info", "ready-for-agent", "ready-for-human", "wontfix")


def outcome_args(outcome):
    """The --category an outcome takes: bug for a ready one, none for a
    closing one."""
    return ["--category", "bug"] if outcome.startswith("ready-") else []


@pytest.mark.parametrize("outcome", ["close-fixed", "wontfix", "ready-for-agent", "ready-for-human"])
def test_a_finding_carrying_every_triage_role_ends_in_the_one_its_outcome_sets(
    orch, seed, store, comment, outcome
):
    triaged(seed, 6, "review:major", *EVERY_ROLE, "bug")

    assert orch("apply", "6", outcome, *outcome_args(outcome),
                "--comment-file", str(comment))[0] == 0
    left = {"close-fixed": [], "wontfix": ["wontfix"]}.get(outcome, [outcome])
    assert sorted(labels_of(store, 6)) == sorted(["bug", "review:major"] + left)


class RelabelLog(FakeGh):
    """The gh fake, logging the labels each relabel names for removal, as
    gh's argv would carry them."""

    removed = []

    def issue_relabel(self, n, add=(), remove=()):
        RelabelLog.removed.extend(remove)
        super().issue_relabel(n, add=add, remove=remove)


@pytest.mark.parametrize(
    "outcome, labels, removed",
    [("close-fixed", ["ready-for-agent"], ["ready-for-agent"]),
     ("wontfix", ["needs-triage"], ["needs-triage"]),
     ("ready-for-agent", ["ready-for-human"], ["ready-for-human"]),
     ("ready-for-human", ["ready-for-agent"], ["ready-for-agent"]),
     ("ready-for-agent", ["ready-for-agent"], [])],
    ids=["close-fixed", "wontfix", "to-agent", "to-human", "own-state"],
)
def test_apply_removes_only_the_triage_labels_the_finding_carries(
    orch, seed, store, comment, outcome, labels, removed
):
    triaged(seed, 7, "review:minor", *labels, "bug")
    orch.gh_class = RelabelLog
    RelabelLog.removed = []

    assert orch("apply", "7", outcome, *outcome_args(outcome),
                "--comment-file", str(comment))[0] == 0
    assert RelabelLog.removed == removed


