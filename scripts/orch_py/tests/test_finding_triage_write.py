"""finding-triage apply and bundle in-process, against the gh fake on a
tmp_path store: each checked by its stdout, its exit code, its `orch:`
message and the GitHub state the store holds afterwards. Call order is
checked only where it is the contract: no write before a usage error or a
member check, no comment re-posted, no close after a failed comment.

Every temporary file the verbs make goes under tmp_path/tmp, so a test can
see none is left behind."""
from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path

import pytest

from conftest import (GH_502, checkout, comments_of, labels_doc, labels_of, read, snapshot,
                      write_labels_doc)
from orch import finding_triage
from orch.gh_fake import FakeGh
from orch.repo import RepoPin

DISCLAIMER = "> *This was generated by AI during triage.*"
COMMENT = "Fixed by abc1234 on main.\n"
POSTED = DISCLAIMER + "\n\n" + COMMENT


class Noun:
    """`orch.sh finding-triage ...` in-process: the fake gh on <seed>'s
    store - <gh_class>, FakeGh or a subclass - the fake checkout <git> - its triage-labels doc written by
    labels_doc() - <env> for the host the messages name, and the temporary
    files made by <mkstemp>, under <tmp>."""

    def __init__(self, seed, git, tmp, capsys):
        self.seed = seed
        self.git = git
        self.tmp = tmp
        self.capsys = capsys
        self.env = {}
        self.gh_class = FakeGh
        self.mkstemp = lambda: tempfile.mkstemp(dir=str(tmp))

    def labels_doc(self, *rows):
        """The repo's triage-labels doc, mapping each (role, label) row."""
        write_labels_doc(Path(self.git.root), labels_doc(*rows))

    def __call__(self, *argv):
        """(exit code, stdout, stderr) of `orch.sh finding-triage <argv>`."""
        pin = RepoPin(self.env, self.git)
        gh = self.gh_class(self.seed.store, self.env, pin=pin, sleep=lambda _: None)
        try:
            code = finding_triage.run(list(argv), gh=gh, git=self.git, env=self.env, pin=pin,
                                      mkstemp=self.mkstemp)
        except SystemExit as died:
            code = died.code
        out, err = self.capsys.readouterr()
        return code, out, err

    def leftovers(self):
        """The temporary files the verbs left behind."""
        return sorted(os.listdir(str(self.tmp)))


@pytest.fixture
def orch(seed, tmp_path, capsys):
    tmp = tmp_path / "tmp"
    tmp.mkdir()
    noun = Noun(seed, checkout(tmp_path), tmp, capsys)
    yield noun
    assert noun.leftovers() == [], "a temporary file was left behind"


@pytest.fixture
def comment(tmp_path):
    path = tmp_path / "comment.md"
    path.write_text(COMMENT)
    return path


def triaged(seed, n, *labels, state="open"):
    """Filed finding #n in the store, carrying <labels>."""
    seed.issue(n, state, *labels)
    seed.body(n, "**Axis:** Spec\n")


def state_of(store, n):
    """Issue #n's state and its close reason, as the store holds them."""
    return ((read(store, "issues", n, "state") or "").rstrip("\n"),
            (read(store, "issues", n, "reason") or "").rstrip("\n"))


