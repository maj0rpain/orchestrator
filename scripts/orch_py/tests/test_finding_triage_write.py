    orch.mkstemp = unwritable_temp_file(orch.tmp)

    assert orch("apply", "2", "close-fixed", "--comment-file", str(comment)) == (
        1, "", "orch: could not write the triage comment from %s - nothing was posted on"
               " issue #2\n" % comment)
    assert comments_of(store, 2) == []


